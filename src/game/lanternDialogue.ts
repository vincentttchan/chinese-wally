export function lanternReplyFor(id: string, visit: number): string {
  const item = lanternVoices[id];
  if (!item) return '咦，你在找誰呀？';
  // The greeting happens once; later clicks alternate that person's two replies.
  return item.lines[visit === 0 ? 0 : 1 + ((visit - 1) % 2)];
}
